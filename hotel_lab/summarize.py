"""Generate platform-style review summaries with ONE fixed summariser prompt (brief, step 6).

Output goes to runs/_summaries/<model>/<scenario>.yaml for two team members to check.
Only after that check, copy them into the `summaries:` block of the stimulus file.
"""
from __future__ import annotations

from pathlib import Path

import yaml

from hotel_lab import RUNS_DIR
from hotel_lab.models import ModelClient, ModelConfig
from hotel_lab.stimuli import Scenario

SUMMARISER_PROMPT = """You write the short review summary shown on a hotel booking website.
Summarise the guest reviews below in 2 to 3 neutral sentences. Mention the main positives and the main
negatives in proportion to how often guests raise them. Do not add anything the reviews do not say.
Do not mention star ratings or numbers of reviews. Output only the summary text.

Reviews:
{reviews}"""


def summarize(scenarios: list[Scenario], model_name: str, sets: list[str] | None = None) -> Path:
    cfg = ModelConfig.load(model_name)
    client = ModelClient(cfg)
    out_dir = RUNS_DIR / "_summaries" / cfg.name
    out_dir.mkdir(parents=True, exist_ok=True)
    for sc in scenarios:
        result = {"_note": f"Generated by {cfg.name} ({cfg.model}) with the fixed prompt in hotel_lab/summarize.py. "
                           "UNVERIFIED: two coders must check before use.",
                  "_prompt": SUMMARISER_PROMPT}
        for room in sc.rooms:
            pool = {r["review_id"]: r for r in room["review_pool"]}
            result[room["room_id"]] = {}
            for sname, ids in room["review_sets"].items():
                if sets and sname not in sets:
                    continue
                reviews = "\n".join(f"- {pool[i]['title']}: {pool[i]['text']['base']}" for i in ids)
                comp = client.complete(SUMMARISER_PROMPT.replace("{reviews}", reviews), seed=0)
                result[room["room_id"]][sname] = comp.text.strip()
        with open(out_dir / f"{sc.id}.yaml", "w", encoding="utf-8") as f:
            yaml.safe_dump(result, f, allow_unicode=True, sort_keys=False, width=100)
    return out_dir
